import sbt.*

/** Generates `api.migration.GeneratedOneTimeMigrations`, the list of every one-time migration this build runs,
  * from the migration classes themselves (ISS-21839), through [[RegisteredByExistence]].
  *
  * A migration is registered by existing: a concrete class in any `app` source tree `api` depends on, whose
  * header names `OneTimeMigration` directly after `extends` or `with`. Adding one is writing its class; pruning
  * one is deleting its class and its spec. No shared file is edited for either, so prunes and backfills landing
  * the same hour never conflict on a registry, and a merge can never drop one silently.
  *
  * Order inside the list is not meaningful: the generated list is sorted by class name, and
  * `api.migration.AllOneTimeMigrations` orders it from each migration's own `runsAfter`.
  */
object OneTimeMigrationRegistry {

  val GeneratedPackage: String = "api.migration"
  val GeneratedClass: String = "GeneratedOneTimeMigrations"

  /** The generated source for `classes`: one injected constructor parameter per migration. */
  def render(classes: Seq[String]): String = {
    val params = classes.zipWithIndex.map { case (c, i) => s"  m$i: _root_.$c," }
    val elements = if (classes.isEmpty) "Nil" else classes.indices.map(i => s"m$i").mkString("Seq(", ", ", ")")
    s"""package $GeneratedPackage
       |
       |// GENERATED by scala-build-app's OneTimeMigrationRegistry.scala from every class extending OneTimeMigration.
       |// Never edit: add a migration by writing its class, prune one by deleting its class.
       |
       |@_root_.javax.inject.Singleton
       |class $GeneratedClass @_root_.javax.inject.Inject() (
       |${params.mkString("\n")}
       |) {
       |  val all: Seq[_root_.core.migration.OneTimeMigration] = $elements
       |}
       |""".stripMargin
  }

  val registry: RegisteredByExistence.Registry = RegisteredByExistence.Registry(
    marker = "core.migration.OneTimeMigration",
    file = s"one-time-migrations/$GeneratedClass.scala",
    render = render,
  )

  /** The source generator `api` registers: every subproject `api` depends on may declare a migration. */
  def generator: Def.Initialize[Task[Seq[File]]] = RegisteredByExistence.generator(includeDependencies = true, registry)
}
