import sbt.*

/** Generates `core.autonomy.GeneratedAutonomyWorkflows`, every object extending `AutonomyWorkflowDeclaration` in
  * `core`, through [[RegisteredByExistence]] (ISS-25155).
  *
  * A workflow of `core` is registered by existing: its declaration and its action names are one object in one file under
  * `core/app/core/autonomy/workflows`, so adding a workflow edits no shared file and two workflows in flight never
  * conflict on the catalog. `core.autonomy.CoreAutonomyWorkflows` declares the generated list through the same
  * `ServiceLoader` seam a product subproject declares its own workflows through, and
  * `core.autonomy.AutonomyWorkflowCatalog.All` is every declaration on the classpath (ISS-89309).
  */
object AutonomyWorkflowRegistry {

  private val GeneratedClass: String = "GeneratedAutonomyWorkflows"

  /** The generated source for `objects`: one reference per declaration, in the sorted order given. */
  def render(objects: Seq[String]): String = {
    val elements = if (objects.isEmpty) "Nil" else objects.map(o => s"    _root_.$o,").mkString("Seq(\n", "\n", "\n  )")
    s"""package core.autonomy
       |
       |// GENERATED by scala-build-app's AutonomyWorkflowRegistry.scala from every object extending AutonomyWorkflowDeclaration.
       |// Never edit: add a workflow by writing its object, remove one by deleting its object.
       |
       |object $GeneratedClass {
       |  val all: Seq[_root_.core.autonomy.AutonomyWorkflowDeclaration] = $elements
       |}
       |""".stripMargin
  }

  val registry: RegisteredByExistence.Registry = RegisteredByExistence.Registry(
    marker = "core.autonomy.AutonomyWorkflowDeclaration",
    file = s"autonomy-workflows/$GeneratedClass.scala",
    render = render,
    members = RegisteredByExistence.Objects,
  )

  /** The source generator `core` registers. Only `core`'s own sources are read: a product subproject names its workflows
    * in its own `AutonomyWorkflowDeclarations`.
    */
  def generator: Def.Initialize[Task[Seq[File]]] =
    RegisteredByExistence.generator(includeDependencies = false, registry)
}
